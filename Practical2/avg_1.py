marks = float(input("Enter your marks: "))

if marks >= 90:
    print("Excellent performance! You scored an A grade.")
elif marks >= 80:
    print("very good performance! You scored a B grade.")    
elif marks >= 70:
    print("Good performance! You scored a C grade.")    
elif marks >= 60:
    print("Average performance! You scored a D grade.")
else:
    print("Poor performance! You scored an F grade.")    